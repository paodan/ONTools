#' Build amplicon variant delivery packages
#'
#' `make_variant_delivery()` runs the ONT amplicon variant-calling delivery
#' workflow: optional Dorado basecalling/demultiplexing, run-level QC, grouping
#' demultiplexed barcode FASTQ folders by sample information, running
#' `wf-amplicon` in reference-based variant-calling mode, generating per-barcode
#' `variant.tsv` files from `medaka.annotated.vcf.gz`, writing a group-level
#' `variant_all.tsv`, optional filtered-read QC, optional IGV snapshots,
#' optional synthetic AB1 chromatograms, and final result collection.
#'
#' @param path_proj MinKNOW project directory.
#' @param path_sampleInfo_file_list Named character vector or list of sample
#'   information CSV files. Names are used as grouped FASTQ folder names.
#' @param reference Reference FASTA file passed to [run_wf_amplicon()] and
#'   used for downstream variant tables, IGV snapshots, and AB1 traces. After
#'   [run_wf_amplicon()] finishes, downstream steps first try to use the
#'   workflow-generated `reference_sanitized_seqID.*` file under each `out_dir`
#'   so reference record names match VCF `CHROM` and BAM contig names.
#' @param path_delivery Root directory where per-group final results are copied.
#' @param kit_name Dorado barcode kit name.
#' @param model Dorado basecalling model or model alias.
#' @param demux_out Demux output directory name under `path_proj`. If `NULL`,
#'   defaults to `demux_out_<kit_name>`.
#' @param fastq_out FASTQ output directory name created by Dorado conversion.
#' @param barcode_both_ends Logical. Passed to [dorado_demux_bam()].
#' @param run_basecalling_demux_step Logical. If `FALSE`, reuse
#'   `work/stat.Rdata` when present or reconstruct output paths from
#'   `path_proj`, `demux_out`, and `fastq_out`.
#' @param run_dorado_basecall_step Logical. Run Dorado basecalling.
#' @param run_dorado_demux_step Logical. Run Dorado barcode demultiplexing.
#' @param run_dorado_fastq_step Logical. Convert demultiplexed BAM files to
#'   FASTQ.GZ files.
#' @param run_QC_step Logical. Generate run-level QC plots and source FASTQ
#'   statistics.
#' @param move_fastq_step Logical. Move barcode FASTQ folders into sample-info
#'   groups before running amplicon analysis.
#' @param move_fastq_mode FASTQ grouping mode: `"move"`, `"reuse"`, or `"auto"`.
#' @param run_amplicon_step Logical. Run [run_wf_amplicon()] for each group.
#' @param make_variant_table_step Logical. Generate per-barcode `variant.tsv`
#'   files and group-level `variant_all.tsv`.
#' @param run_filtered_QC_step Logical. Generate QC plots for filtered reads for
#'   each group.
#' @param run_igv_step Logical. Generate IGV snapshots from
#'   `barcode*/alignments/*.bam` against `reference`.
#' @param make_ab1 Logical. If `TRUE`, create synthetic AB1 chromatogram files
#'   from `barcode*/alignments/*.bam` and `reference`.
#' @param ab1_name_template Output AB1 filename template. `{barcode}` is
#'   replaced by the barcode folder name and `{reference}` is replaced by the
#'   FASTA record name.
#' @param ab1_samtools Command name or full path used by
#'   [synthetic_ab1_from_bam()] to launch `samtools`.
#' @param igv_dir_name Directory name under each barcode folder for IGV
#'   snapshots.
#' @param ab1_dir_name Directory name under each barcode folder for synthetic
#'   AB1 files.
#' @param collect_results_step Logical. Copy final deliverables into
#'   `path_delivery`.
#' @param variant_vcf_name VCF filename under each `barcode*/variants/`
#'   directory.
#' @param variant_tsv_name Per-barcode variant TSV filename to write.
#' @param variant_all_name Group-level merged variant TSV filename to write next
#'   to the `barcode*` directories.
#' @param variant_columns Columns kept in `variant.tsv` and `variant_all.tsv`.
#' @param flank_width Number of reference bases passed to [read_vcf()] for
#'   upstream/downstream sequence extraction.
#' @param project_col,amplicon_size_col,barcode_col Column names in each sample
#'   information file.
#' @param min_read_length_col,max_read_length_col Read-length filter column
#'   names in each sample information file.
#' @param min_read_qual,min_n_reads,force_spoa_length_threshold,override_basecaller_cfg,profile,resume
#'   Parameters passed to [run_wf_amplicon()].
#' @param amplicon_extra_args Optional raw command-line string appended to each
#'   [run_wf_amplicon()] call.
#' @param barcode_digits Number of barcode digits used by [plot_seqQC()] for
#'   filtered-read QC.
#' @param dorado_threads Optional thread count passed to [dorado_demux_bam()].
#' @param dorado_fastq_write_md5 Logical. If `TRUE`, write MD5 checksum files
#'   next to FASTQ.GZ files generated by [dorado_bam_to_fastq()].
#' @param dorado,samtools,gzip Command names or executable paths used by the
#'   split Dorado steps.
#' @param dorado_conda_env Optional conda environment used by the split Dorado,
#'   samtools, and gzip steps.
#' @param conda Conda executable name or path.
#' @param overwrite_fastq Logical. Passed to [move_fastq_to_folders()].
#' @param overwrite_delivery Logical. Replace existing files/directories in the
#'   final delivery directory.
#' @param include_execution Logical. Copy the workflow `execution` directory
#'   when present.
#' @param igv IGV executable path passed to [igv_snapshot()].
#' @param igv_format Snapshot image format passed to [igv_snapshot()].
#' @param igv_sort,igv_display,max_panel_height,use_xvfb IGV rendering options
#'   passed to [igv_snapshot()].
#' @param dry_run Logical. If `TRUE`, build plans and commands without running
#'   external analysis steps or copying final deliverables.
#' @param echo Logical. If `TRUE`, print commands from wrapped command runners.
#' @param wait Logical. Passed to wrapped command runners.
#' @param stdout,stderr Passed to wrapped command runners.
#'
#' @return Invisibly returns a list with run-level QC (`g1`), per-group QC
#'   (`g2`), Dorado/basecalling status (`stat`), FASTQ move plans, amplicon
#'   workflow results, sanitized reference paths used for downstream variant
#'   outputs, variant table summaries, IGV snapshot summaries, synthetic AB1
#'   summaries, delivery copy summaries, and important output paths.
#'
#' @export
make_variant_delivery <- function(path_proj,
                                  path_sampleInfo_file_list,
                                  reference,
                                  path_delivery = "/data/project_delivery",
                                  kit_name = "YS-NB576",
                                  model = "sup",
                                  demux_out = NULL,
                                  fastq_out = "fastq_pass_trim",
                                  barcode_both_ends = FALSE,
                                  run_basecalling_demux_step = TRUE,
                                  run_dorado_basecall_step = run_basecalling_demux_step,
                                  run_dorado_demux_step = run_basecalling_demux_step,
                                  run_dorado_fastq_step = run_basecalling_demux_step,
                                  run_QC_step = TRUE,
                                  move_fastq_step = TRUE,
                                  move_fastq_mode = c("move", "reuse", "auto"),
                                  run_amplicon_step = TRUE,
                                  make_variant_table_step = TRUE,
                                  run_filtered_QC_step = TRUE,
                                  run_igv_step = TRUE,
                                  make_ab1 = TRUE,
                                  ab1_name_template = "{barcode}.{reference}.synthetic.ab1",
                                  ab1_samtools = "samtools",
                                  igv_dir_name = "IGV",
                                  ab1_dir_name = "AB1",
                                  collect_results_step = TRUE,
                                  variant_vcf_name = "medaka.annotated.vcf.gz",
                                  variant_tsv_name = "variant.tsv",
                                  variant_all_name = "variant_all.tsv",
                                  variant_columns = c(
                                    "CHROM",
                                    "reference_name_original",
                                    "reference_name_sanitized",
                                    "POS", "REF", "ALT", "QUAL", "FILTER", "Type",
                                    "ref_depth_downsampled", "alt_depth_downsampled",
                                    "variant_percent", "sampleID",
                                    "ref_upstream_20bp", "ref_downstream_20bp"
                                  ),
                                  flank_width = 20,
                                  project_col = "Project_ID",
                                  amplicon_size_col = "Expected_Size_bp",
                                  barcode_col = "Barcode_ID",
                                  min_read_length_col = "Min_Read_Length",
                                  max_read_length_col = "Max_Read_Length",
                                  min_read_qual = 10,
                                  min_n_reads = 40,
                                  force_spoa_length_threshold = 2000,
                                  override_basecaller_cfg = "dna_r10.4.1_e8.2_400bps_sup@v5.2.0",
                                  profile = "standard",
                                  resume = TRUE,
                                  amplicon_extra_args = NULL,
                                  barcode_digits = 3,
                                  dorado_threads = NULL,
                                  dorado_fastq_write_md5 = TRUE,
                                  dorado = "dorado",
                                  samtools = "samtools",
                                  gzip = "gzip",
                                  dorado_conda_env = NULL,
                                  conda = "conda",
                                  overwrite_fastq = FALSE,
                                  overwrite_delivery = TRUE,
                                  include_execution = FALSE,
                                  igv = "/usr/local/bin/IGV_Linux_2.19.8/igv.sh",
                                  igv_format = "png",
                                  igv_sort = "base",
                                  igv_display = "collapse",
                                  max_panel_height = NULL,
                                  use_xvfb = FALSE,
                                  dry_run = FALSE,
                                  echo = TRUE,
                                  wait = TRUE,
                                  stdout = "",
                                  stderr = "") {
  check_dir_arg(path_proj, "path_proj")
  check_file_arg(reference, "reference")
  check_scalar_character(path_delivery, "path_delivery")
  check_scalar_character(kit_name, "kit_name")
  check_scalar_character(model, "model")
  check_scalar_character(fastq_out, "fastq_out")
  check_scalar_character(variant_vcf_name, "variant_vcf_name")
  check_scalar_character(variant_tsv_name, "variant_tsv_name")
  check_scalar_character(variant_all_name, "variant_all_name")
  if (!is.character(variant_columns) || length(variant_columns) == 0L ||
      anyNA(variant_columns) || any(!nzchar(variant_columns))) {
    stop("`variant_columns` must be a non-empty character vector.", call. = FALSE)
  }
  check_scalar_character(project_col, "project_col")
  check_scalar_character(amplicon_size_col, "amplicon_size_col")
  check_scalar_character(barcode_col, "barcode_col")
  check_scalar_character(min_read_length_col, "min_read_length_col")
  check_scalar_character(max_read_length_col, "max_read_length_col")
  check_scalar_character(override_basecaller_cfg, "override_basecaller_cfg")
  check_scalar_character(profile, "profile")
  check_scalar_character(dorado, "dorado")
  check_scalar_character(samtools, "samtools")
  check_scalar_character(gzip, "gzip")
  check_scalar_character(conda, "conda")
  check_logical_scalar(barcode_both_ends, "barcode_both_ends")
  check_logical_scalar(run_basecalling_demux_step, "run_basecalling_demux_step")
  check_logical_scalar(run_dorado_basecall_step, "run_dorado_basecall_step")
  check_logical_scalar(run_dorado_demux_step, "run_dorado_demux_step")
  check_logical_scalar(run_dorado_fastq_step, "run_dorado_fastq_step")
  check_logical_scalar(run_QC_step, "run_QC_step")
  check_logical_scalar(move_fastq_step, "move_fastq_step")
  move_fastq_mode <- match.arg(move_fastq_mode)
  check_logical_scalar(run_amplicon_step, "run_amplicon_step")
  check_logical_scalar(make_variant_table_step, "make_variant_table_step")
  check_logical_scalar(run_filtered_QC_step, "run_filtered_QC_step")
  check_logical_scalar(run_igv_step, "run_igv_step")
  check_logical_scalar(make_ab1, "make_ab1")
  check_scalar_character(ab1_name_template, "ab1_name_template")
  check_scalar_character(ab1_samtools, "ab1_samtools")
  check_scalar_character(igv_dir_name, "igv_dir_name")
  check_scalar_character(ab1_dir_name, "ab1_dir_name")
  check_logical_scalar(collect_results_step, "collect_results_step")
  check_logical_scalar(resume, "resume")
  check_logical_scalar(overwrite_fastq, "overwrite_fastq")
  check_logical_scalar(overwrite_delivery, "overwrite_delivery")
  check_logical_scalar(include_execution, "include_execution")
  check_scalar_character(igv, "igv")
  igv_format <- match.arg(igv_format, c("png", "pdf", "svg", "jpg", "jpeg"))
  if (!is.null(igv_sort)) {
    check_scalar_character(igv_sort, "igv_sort")
  }
  if (!is.null(igv_display)) {
    igv_display <- match.arg(igv_display, c("collapse", "expand", "squish"))
  }
  if (!is.null(max_panel_height) &&
      (!is.numeric(max_panel_height) || length(max_panel_height) != 1L ||
       is.na(max_panel_height))) {
    stop("`max_panel_height` must be a single numeric value or `NULL`.",
         call. = FALSE)
  }
  check_logical_scalar(use_xvfb, "use_xvfb")
  check_logical_scalar(dry_run, "dry_run")
  check_logical_scalar(echo, "echo")
  check_logical_scalar(wait, "wait")
  if (!is.null(amplicon_extra_args)) {
    check_scalar_character(amplicon_extra_args, "amplicon_extra_args")
  }

  min_n_reads <- validate_positive_integer(min_n_reads, "min_n_reads")
  force_spoa_length_threshold <- validate_positive_integer(
    force_spoa_length_threshold,
    "force_spoa_length_threshold"
  )
  barcode_digits <- validate_positive_integer(barcode_digits, "barcode_digits")
  flank_width <- validate_nonnegative_integer(flank_width, "flank_width")
  min_read_qual <- validate_nonnegative_number(min_read_qual, "min_read_qual")
  dorado_threads <- validate_optional_positive_integer(dorado_threads, "dorado_threads")
  check_logical_scalar(dorado_fastq_write_md5, "dorado_fastq_write_md5")
  if (!is.null(dorado_conda_env)) {
    check_scalar_character(dorado_conda_env, "dorado_conda_env")
  }
  if (!is.null(demux_out)) {
    check_scalar_character(demux_out, "demux_out")
  }
  if (isTRUE(make_ab1) && !grepl("[{]barcode[}]", ab1_name_template)) {
    stop("`ab1_name_template` must contain `{barcode}`.", call. = FALSE)
  }

  path_proj <- normalizePath(path_proj, mustWork = TRUE)
  reference <- normalizePath(reference, mustWork = TRUE)
  path_sampleInfo_file_list <- validate_sample_info_file_list(
    path_sampleInfo_file_list
  )
  demux_out_name <- if (is.null(demux_out)) paste0("demux_out_", kit_name) else demux_out

  path_work <- file.path(path_proj, "work")
  dir.create(path_work, showWarnings = FALSE, recursive = TRUE)
  dir.create(path_delivery, showWarnings = FALSE, recursive = TRUE)
  if (dir.exists(path_delivery)) {
    path_delivery <- normalizePath(path_delivery, mustWork = TRUE)
  } else if (isTRUE(dry_run)) {
    path_delivery <- normalizePath(path_delivery, mustWork = FALSE)
  } else {
    stop("Could not create `path_delivery`: ", path_delivery, call. = FALSE)
  }

  stat <- run_variant_dorado_steps(
    path_proj = path_proj,
    path_work = path_work,
    kit_name = kit_name,
    model = model,
    demux_out_name = demux_out_name,
    fastq_out = fastq_out,
    barcode_both_ends = barcode_both_ends,
    run_dorado_basecall_step = run_dorado_basecall_step,
    run_dorado_demux_step = run_dorado_demux_step,
    run_dorado_fastq_step = run_dorado_fastq_step,
    dorado_threads = dorado_threads,
    dorado_fastq_write_md5 = dorado_fastq_write_md5,
    dorado = dorado,
    samtools = samtools,
    gzip = gzip,
    dorado_conda_env = dorado_conda_env,
    conda = conda,
    dry_run = dry_run,
    echo = echo,
    wait = wait,
    stderr = stderr
  )

  if (!isTRUE(run_dorado_basecall_step) &&
      !isTRUE(run_dorado_demux_step) &&
      !isTRUE(run_dorado_fastq_step)) {
    message("Step 1: Dorado basecalling, demultiplexing, and FASTQ conversion (skipped)")
    stat_file <- file.path(path_work, "stat.Rdata")
    if (file.exists(stat_file)) {
      load(stat_file)
    } else {
      stat <- list(
        command = NA_character_,
        args = character(),
        status = NA_integer_,
        paths = dorado_demux_to_fastq_paths(
          proj = path_proj,
          model = model,
          demux_out = demux_out_name,
          fastq_out = fastq_out,
          scan_dynamic = TRUE
        )
      )
    }
  }

  fastq_root <- select_single_path(
    stat$paths$fastq_dirs,
    "FASTQ output directory",
    fallback = if (isTRUE(dry_run)) file.path(stat$paths$demux_dir, "<run_dir>", fastq_out) else NA_character_
  )
  run_root <- select_single_path(
    stat$paths$run_dirs,
    "Dorado run directory",
    fallback = if (isTRUE(dry_run)) file.path(stat$paths$demux_dir, "<run_dir>") else NA_character_
  )
  path_seq_summary <- file.path(stat$paths$demux_dir, "sequencing_summary.txt")
  message("Sequencing summary is saved here: ", path_seq_summary)

  fig_path <- file.path(stat$paths$demux_dir, "figs", "png")
  stat_path <- file.path(stat$paths$demux_dir, "stats")
  dir.create(fig_path, showWarnings = FALSE, recursive = TRUE)
  dir.create(stat_path, showWarnings = FALSE, recursive = TRUE)

  g1 <- NULL
  source_fastq_stats <- NULL
  if (isTRUE(run_QC_step)) {
    qc <- run_variant_source_qc(
      path_seq_summary = path_seq_summary,
      fastq_root = fastq_root,
      model = model,
      fig_path = fig_path,
      stat_path = stat_path,
      dry_run = dry_run
    )
    g1 <- qc$plot
    source_fastq_stats <- qc$source_fastq_stats
  } else {
    message("Step 2: Making QC plots for all samples (skipped)")
  }

  move_plans <- list()
  workflow <- list()
  variant_tables <- list()
  variant_references <- list()
  g2 <- list()
  igv_results <- list()
  ab1_results <- list()
  delivery <- list()

  for (folder in names(path_sampleInfo_file_list)) {
    message(folder)
    sample_info_file <- path_sampleInfo_file_list[[folder]]
    sample_info <- read_sample_info_table(sample_info_file)
    sample_barcode_col <- resolve_barcode_col(sample_info, barcode_col)
    validate_amplicon_delivery_sample_info(
      sample_info = sample_info,
      required_cols = c(sample_barcode_col, min_read_length_col, max_read_length_col)
    )
    sample_info_sub <- sample_info[1, , drop = FALSE]
    min_read_length <- validate_positive_integer(
      sample_info_sub[[min_read_length_col]],
      min_read_length_col
    )
    max_read_length <- validate_positive_integer(
      sample_info_sub[[max_read_length_col]],
      max_read_length_col
    )
    if (min_read_length > max_read_length) {
      stop("`", min_read_length_col, "` must be less than or equal to `",
           max_read_length_col, "` for group `", folder, "`.", call. = FALSE)
    }

    if (isTRUE(move_fastq_step)) {
      if (is.na(fastq_root)) {
        stop("No FASTQ output directory was found for moving barcode folders.",
             call. = FALSE)
      }
      message("Step 3: Prepare fastq files in group folder")
      reuse_plan <- make_fastq_reuse_plan(
        fastq_dir = fastq_root,
        group = folder,
        sample_info = sample_info,
        barcode_col = sample_barcode_col
      )
      can_reuse_fastq <- all(reuse_plan$destination_exists)

      if (identical(move_fastq_mode, "reuse")) {
        if (!can_reuse_fastq && !isTRUE(dry_run)) {
          stop(
            "Grouped FASTQ folder is incomplete for `", folder, "`. Missing: ",
            paste(reuse_plan$destination[!reuse_plan$destination_exists], collapse = ", "),
            call. = FALSE
          )
        }
        move_plans[[folder]] <- reuse_plan
      } else if (identical(move_fastq_mode, "auto") && can_reuse_fastq) {
        message("Step 3: Reusing existing grouped FASTQ folder for ", folder)
        move_plans[[folder]] <- reuse_plan
      } else if (isTRUE(dry_run) && !dir.exists(fastq_root)) {
        move_plans[[folder]] <- make_fastq_move_plan_without_source_dir(
          fastq_dir = fastq_root,
          sample_info = sample_info,
          project_col = project_col,
          amplicon_size_col = amplicon_size_col,
          barcode_col = sample_barcode_col
        )
      } else {
        move_plans[[folder]] <- move_fastq_to_folders(
          fastq_dir = fastq_root,
          sample_info = sample_info_file,
          project_col = project_col,
          amplicon_size_col = amplicon_size_col,
          barcode_col = barcode_col,
          overwrite = overwrite_fastq,
          dry_run = dry_run
        )
      }
    } else {
      message("Step 3: Move fastq files to a folder (skipped)")
      move_plans[[folder]] <- NULL
    }

    group_fastq <- if (is.na(fastq_root)) NA_character_ else file.path(fastq_root, folder)
    group_out_dir <- if (is.na(run_root)) {
      file.path(stat$paths$demux_dir, "results", "wf_amplicon_variant", folder)
    } else {
      file.path(run_root, "results", "wf_amplicon_variant", folder)
    }

    if (isTRUE(run_amplicon_step)) {
      message("Step 4: Run amplicon variant workflow")
      workflow[[folder]] <- run_wf_amplicon(
        fastq = group_fastq,
        out_dir = group_out_dir,
        reference = reference,
        min_read_length = min_read_length,
        max_read_length = max_read_length,
        min_read_qual = min_read_qual,
        min_n_reads = min_n_reads,
        force_spoa_length_threshold = force_spoa_length_threshold,
        override_basecaller_cfg = override_basecaller_cfg,
        profile = profile,
        resume = resume,
        extra_args = amplicon_extra_args,
        dry_run = dry_run,
        echo = echo,
        wait = wait,
        stdout = stdout,
        stderr = stderr
      )
    } else {
      message("Step 4: Run amplicon variant workflow (skipped)")
      workflow[[folder]] <- list(
        status = NA_integer_,
        paths = list(fastq = group_fastq, out_dir = group_out_dir, reference = reference)
      )
    }
    variant_reference <- resolve_wf_amplicon_variant_reference(
      result_dir = workflow[[folder]]$paths$out_dir,
      reference = reference,
      dry_run = dry_run
    )
    variant_references[[folder]] <- variant_reference

    if (isTRUE(make_variant_table_step)) {
      message("Step 5: Generate variant tables")
      variant_tables[[folder]] <- make_wf_amplicon_variant_tables(
        result_dir = workflow[[folder]]$paths$out_dir,
        reference = variant_reference,
        original_reference = reference,
        variant_vcf_name = variant_vcf_name,
        variant_tsv_name = variant_tsv_name,
        variant_all_name = variant_all_name,
        variant_columns = variant_columns,
        flank_width = flank_width,
        dry_run = dry_run
      )
    } else {
      message("Step 5: Generate variant tables (skipped)")
      variant_tables[[folder]] <- NULL
    }

    if (isTRUE(run_filtered_QC_step)) {
      if (!file.exists(path_seq_summary)) {
        if (isTRUE(dry_run)) {
          message("Step 6: Run QC plots for filtered reads (dry-run; sequencing summary not found)")
          g2[[folder]] <- NULL
        } else {
          stop("Sequencing summary file not found: ", path_seq_summary, call. = FALSE)
        }
      } else {
        message("Step 6: Run QC plots for filtered reads")
        barcode_numbers <- barcode_ids_to_numbers(sample_info[[sample_barcode_col]])
        g2[[folder]] <- plot_seqQC(
          filePath = path_seq_summary,
          runName = model,
          device = "png",
          barcodes = barcode_numbers,
          barcode_digits = barcode_digits,
          min_read_length = min_read_length,
          max_read_length = max_read_length,
          filename_suffix = "_filtered",
          sample_len_dir_mode = "fastq_pass_trim",
          fastq_pass_trim_dir = workflow[[folder]]$paths$fastq,
          plot_unclassified = FALSE
        )

        ggplot2::ggsave(
          filename = file.path(workflow[[folder]]$paths$out_dir, "numRead_perSample.png"),
          plot = g2[[folder]]$numRead,
          width = 12,
          height = 8
        )
        ggplot2::ggsave(
          filename = file.path(workflow[[folder]]$paths$out_dir, "lenReadDistribution.png"),
          plot = g2[[folder]]$lenRead,
          width = 15,
          height = 15
        )
        utils::write.csv(
          g2[[folder]]$read_counts,
          file = file.path(workflow[[folder]]$paths$out_dir, "numRead_perSample.csv")
        )
      }
    } else {
      message("Step 6: Run QC plots for filtered reads (skipped)")
      g2[[folder]] <- NULL
    }

    if (isTRUE(run_igv_step)) {
      message("Step 7: Generate IGV plots")
      igv_results[[folder]] <- generate_variant_igv_snapshots(
        result_dir = workflow[[folder]]$paths$out_dir,
        reference = variant_reference,
        barcode_pattern = "^barcode[0-9]+$",
        format = igv_format,
        igv = igv,
        sort = igv_sort,
        display = igv_display,
        max_panel_height = max_panel_height,
        use_xvfb = use_xvfb,
        igv_dir_name = igv_dir_name,
        dry_run = dry_run
      )
    } else {
      message("Step 7: Generate IGV plots (skipped)")
      igv_results[[folder]] <- NULL
    }

    if (isTRUE(make_ab1)) {
      message("Step 8: Generate synthetic AB1 files")
      ab1_results[[folder]] <- generate_variant_ab1_files(
        result_dir = workflow[[folder]]$paths$out_dir,
        reference = variant_reference,
        barcode_pattern = "^barcode[0-9]+$",
        ab1_name_template = ab1_name_template,
        ab1_dir_name = ab1_dir_name,
