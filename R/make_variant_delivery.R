          ab1 = ab1,
          reference_exists = file.exists(reference),
          bam_exists = bam_exists,
          bai_exists = bai_exists,
          generated = FALSE,
          status = "dry_run",
          stringsAsFactors = FALSE
        ))
        next
      }

      if (!bam_exists) {
        stop("BAM file not found for `", barcode, "`: ", bam, call. = FALSE)
      }
      if (!bai_exists) {
        stop("BAM index not found for `", barcode, "`: ", paste0(bam, ".bai"),
             call. = FALSE)
      }

      synthetic_ab1_from_bam(
        consensus = reference,
        bam = bam,
        output_ab1 = ab1,
        reference_name = ref_name,
        sample = paste(barcode, ref_name, sep = "_"),
        samtools = samtools,
        overwrite = overwrite,
        echo = echo,
        stderr = stderr
      )

      rows <- rbind(rows, data.frame(
        barcode = barcode,
        reference_name = ref_name,
        reference = reference,
        bam = bam,
        bai = bai,
        ab1 = normalizePath(ab1, mustWork = TRUE),
        reference_exists = file.exists(reference),
        bam_exists = bam_exists,
        bai_exists = bai_exists,
        generated = TRUE,
        status = "generated",
        stringsAsFactors = FALSE
      ))
    }
  }

  rows
}

variant_barcode_dirs <- function(result_dir, barcode_pattern) {
  barcode_dirs <- if (dir.exists(result_dir)) {
    list.dirs(result_dir, recursive = FALSE, full.names = TRUE)
  } else {
    character()
  }
  barcode_dirs <- barcode_dirs[grepl(barcode_pattern, basename(barcode_dirs))]
  sort(barcode_dirs)
}

variant_reference_names <- function(reference) {
  records <- Biostrings::readDNAStringSet(reference)
  if (length(records) == 0L) {
    stop("No FASTA records found in `reference`.", call. = FALSE)
  }
  ref_names <- names(records)
  if (is.null(ref_names) || any(!nzchar(ref_names))) {
    stop("All FASTA records in `reference` must have names.", call. = FALSE)
  }
  ref_names
}

collect_variant_results <- function(result_dir,
                                    output_dir,
                                    sample_map = NULL,
                                    variant_all_name = "variant_all.tsv",
                                    barcode_pattern = "^barcode[0-9]+$",
                                    fastq_pass_trim_dir = NULL,
                                    sample_length_plot_pattern = "^Distribution_seqLength__.*\\.png$",
                                    include_execution = FALSE,
                                    include_igv = FALSE,
                                    include_ab1 = FALSE,
                                    ab1_name_template = "{barcode}.{reference}.synthetic.ab1",
                                    igv_dir_name = "IGV",
                                    ab1_dir_name = "AB1",
                                    readme_name = "README.txt",
                                    chinese_readme_name = "README.zh-CN.txt",
                                    overwrite = TRUE) {
  check_dir_arg(result_dir, "result_dir")
  check_scalar_character(output_dir, "output_dir")
  check_scalar_character(variant_all_name, "variant_all_name")
  check_scalar_character(barcode_pattern, "barcode_pattern")
  check_scalar_character(sample_length_plot_pattern, "sample_length_plot_pattern")
  check_scalar_character(readme_name, "readme_name")
  check_logical_scalar(include_igv, "include_igv")
  check_logical_scalar(include_ab1, "include_ab1")
  check_scalar_character(ab1_name_template, "ab1_name_template")
  check_scalar_character(igv_dir_name, "igv_dir_name")
  check_scalar_character(ab1_dir_name, "ab1_dir_name")
  if (!is.null(chinese_readme_name)) {
    check_scalar_character(chinese_readme_name, "chinese_readme_name")
  }
  check_logical_scalar(include_execution, "include_execution")
  check_logical_scalar(overwrite, "overwrite")

  result_dir <- normalizePath(result_dir, mustWork = TRUE)
  if (!is.null(sample_map)) {
    check_file_arg(sample_map, "sample_map")
    sample_map <- normalizePath(sample_map, mustWork = TRUE)
  }
  if (!is.null(fastq_pass_trim_dir)) {
    check_dir_arg(fastq_pass_trim_dir, "fastq_pass_trim_dir")
    fastq_pass_trim_dir <- normalizePath(fastq_pass_trim_dir, mustWork = TRUE)
  }

  dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
  output_dir <- normalizePath(output_dir, mustWork = TRUE)

  barcode_dirs <- list.dirs(result_dir, recursive = FALSE, full.names = TRUE)
  barcode_dirs <- barcode_dirs[grepl(barcode_pattern, basename(barcode_dirs))]
  barcode_dirs <- sort(barcode_dirs)

  items <- data.frame(
    label = character(),
    source = character(),
    destination = character(),
    type = character(),
    exists = logical(),
    copied = logical(),
    stringsAsFactors = FALSE
  )

  items <- rbind(
    items,
    collect_item(
      label = "variant_all",
      source = file.path(result_dir, variant_all_name),
      destination = file.path(output_dir, variant_all_name),
      type = "file",
      overwrite = overwrite
    )
  )

  if (!is.null(sample_map)) {
    items <- rbind(
      items,
      collect_item(
        label = "sample_map",
        source = sample_map,
        destination = file.path(output_dir, basename(sample_map)),
        type = "file",
        overwrite = overwrite
      )
    )
  }

  for (barcode_dir in barcode_dirs) {
    barcode_name <- basename(barcode_dir)
    items <- rbind(
      items,
      collect_item(
        label = barcode_name,
        source = barcode_dir,
        destination = file.path(output_dir, barcode_name),
        type = "directory",
        overwrite = overwrite
      )
    )

    if (!is.null(fastq_pass_trim_dir)) {
      plot_files <- find_sample_length_plots(
        fastq_pass_trim_dir = fastq_pass_trim_dir,
        barcode_name = barcode_name,
        pattern = sample_length_plot_pattern
      )
      for (plot_file in plot_files) {
        items <- rbind(
          items,
          collect_item(
            label = paste0(barcode_name, "_read_length_plot"),
            source = plot_file,
            destination = file.path(output_dir, barcode_name, basename(plot_file)),
            type = "file",
            overwrite = overwrite
          )
        )
      }
    }
  }

  if (isTRUE(include_execution)) {
    items <- rbind(
      items,
      collect_item(
        label = "execution",
        source = file.path(result_dir, "execution"),
        destination = file.path(output_dir, "execution"),
        type = "directory",
        overwrite = overwrite
      )
    )
  }

  readme_path <- file.path(output_dir, readme_name)
  writeLines(
    variant_results_readme(
      variant_all_name = variant_all_name,
      sample_map_name = if (is.null(sample_map)) NULL else basename(sample_map),
      barcode_names = basename(barcode_dirs),
      include_sample_length_plots = !is.null(fastq_pass_trim_dir),
      include_execution = include_execution,
      include_igv = include_igv,
      include_ab1 = include_ab1,
      ab1_name_template = ab1_name_template,
      igv_dir_name = igv_dir_name,
      ab1_dir_name = ab1_dir_name
    ),
    readme_path
  )
  items <- rbind(items, data.frame(
    label = "README",
    source = NA_character_,
    destination = readme_path,
    type = "file",
    exists = TRUE,
    copied = TRUE,
    stringsAsFactors = FALSE
  ))

  if (!is.null(chinese_readme_name)) {
    chinese_readme_path <- file.path(output_dir, chinese_readme_name)
    writeLines(
      variant_results_readme_zh(
        variant_all_name = variant_all_name,
        sample_map_name = if (is.null(sample_map)) NULL else basename(sample_map),
        barcode_names = basename(barcode_dirs),
        include_sample_length_plots = !is.null(fastq_pass_trim_dir),
        include_execution = include_execution,
        include_igv = include_igv,
        include_ab1 = include_ab1,
        ab1_name_template = ab1_name_template,
        igv_dir_name = igv_dir_name,
        ab1_dir_name = ab1_dir_name
      ),
      chinese_readme_path
    )
    items <- rbind(items, data.frame(
      label = "README_zh_CN",
      source = NA_character_,
      destination = chinese_readme_path,
      type = "file",
      exists = TRUE,
      copied = TRUE,
      stringsAsFactors = FALSE
    ))
  }

  invisible(items)
}

variant_results_readme <- function(variant_all_name,
                                   sample_map_name,
                                   barcode_names,
                                   include_sample_length_plots,
                                   include_execution,
                                   include_igv,
                                   include_ab1,
                                   ab1_name_template,
                                   igv_dir_name,
                                   ab1_dir_name) {
  lines <- c(
    "Amplicon variant final results",
    "==============================",
    "",
    "Recommended file",
    "----------------",
    paste0(
      "- ",
      variant_all_name,
      ": merged variant table for all barcode folders in this group."
    ),
    "",
    "Variant table columns",
    "---------------------",
    "- CHROM: reference sequence name used by VCF/BAM/IGV, usually the sanitized wf-amplicon name.",
    "- reference_name_original: original FASTA record name from the user-supplied reference.",
    "- reference_name_sanitized: sanitized FASTA record name used by wf-amplicon, VCF, BAM, and IGV.",
    "- POS: 1-based variant position on the reference.",
    "- REF: reference allele.",
    "- ALT: alternative allele.",
    "- QUAL: variant quality score from the VCF.",
    "- FILTER: VCF filter status.",
    "- Type: variant type inferred from REF and ALT, such as SNP, INDEL, MNP, OTHER, or REF.",
    "- ref_depth_downsampled: strand-summed reference allele support from medaka/wf-amplicon SR.",
    "- alt_depth_downsampled: strand-summed alternative allele support from medaka/wf-amplicon SR.",
    "- variant_percent: alt_depth_downsampled / (ref_depth_downsampled + alt_depth_downsampled) * 100.",
    "- sampleID: VCF sample column name, usually the barcode ID.",
    "- ref_upstream_20bp: 20 bp reference sequence upstream of the edited REF interval.",
    "- ref_downstream_20bp: 20 bp reference sequence downstream of the edited REF interval.",
    "",
    "Other files",
    "-----------"
  )
  if (!is.null(sample_map_name)) {
    lines <- c(
      lines,
      paste0(
        "- ",
        sample_map_name,
        ": barcode-to-sample mapping table. Use this file to match barcode folders to sample names."
      )
    )
  }

  lines <- c(lines, "", "Barcode folders", "---------------")
  if (length(barcode_names) > 0L) {
    lines <- c(
      lines,
      "- barcode*/: per-barcode results copied from the workflow output.",
      "- barcode*/variant.tsv: simplified variant table generated from barcode*/variants/medaka.annotated.vcf.gz.",
      "- barcode*/variants/medaka.annotated.vcf.gz: original medaka annotated VCF from wf-amplicon.",
      "- barcode*/alignments/*.bam: read alignments for the barcode.",
      "- barcode*/alignments/*.bam.bai: BAM index files.",
      if (isTRUE(include_igv)) {
        paste0(
          "- barcode*/",
          igv_dir_name,
          "/<barcode>.<reference>.*: IGV alignment snapshot images generated against the reference FASTA."
        )
      },
      if (isTRUE(include_ab1)) {
        paste0(
          "- barcode*/",
          ab1_dir_name,
          "/",
          sub("[{]reference[}]", "<reference>", sub("[{]barcode[}]", "<barcode>", ab1_name_template)),
          ": synthetic Sanger-style AB1 chromatogram generated from the barcode BAM and reference FASTA."
        )
      },
      if (isTRUE(include_sample_length_plots)) {
        "- barcode*/Distribution_seqLength__*.png: per-barcode read length distribution plot generated from filtered reads."
      },
      "",
      "Included barcode folders:",
      paste0("- ", barcode_names)
    )
  } else {
    lines <- c(lines, "- No barcode folders were found in the source result directory.")
  }

  if (isTRUE(include_execution)) {
    lines <- c(
      lines,
      "",
      "Execution metadata",
      "------------------",
      "- execution/: Nextflow execution report, timeline, and trace files when present."
    )
  }

  c(lines, "")
}

