make_wf_amplicon_variant_tables <- function(result_dir,
                                            reference,
                                            original_reference = reference,
                                            variant_vcf_name,
                                            variant_tsv_name,
                                            variant_all_name,
                                            variant_columns,
                                            flank_width,
                                            dry_run) {
  result_dir_exists <- dir.exists(result_dir)
  barcode_dirs <- if (result_dir_exists) {
    list.dirs(result_dir, recursive = FALSE, full.names = TRUE)
  } else {
    character()
  }
  barcode_dirs <- barcode_dirs[grepl("^barcode[0-9]+$", basename(barcode_dirs))]
  barcode_dirs <- sort(barcode_dirs)
  reference_map <- make_variant_reference_name_map(
    original_reference = original_reference,
    sanitized_reference = reference
  )

  rows <- data.frame(
    barcode = basename(barcode_dirs),
    vcf = file.path(barcode_dirs, "variants", variant_vcf_name),
    variant_tsv = file.path(barcode_dirs, variant_tsv_name),
    exists = file.exists(file.path(barcode_dirs, "variants", variant_vcf_name)),
    n_variants = rep(NA_integer_, length(barcode_dirs)),
    status = rep(if (isTRUE(dry_run)) "dry_run" else "pending", length(barcode_dirs)),
    stringsAsFactors = FALSE
  )
  all_path <- file.path(result_dir, variant_all_name)

  if (isTRUE(dry_run)) {
    return(list(
      result_dir = result_dir,
      variant_all = all_path,
      files = rows,
      status = "dry_run"
    ))
  }
  if (!result_dir_exists) {
    stop("`result_dir` does not exist: ", result_dir, call. = FALSE)
  }
  if (length(barcode_dirs) == 0L) {
    warning("No barcode directories found under: ", result_dir, call. = FALSE)
    variant_all <- empty_variant_table(variant_columns)
    utils::write.table(
      variant_all,
      file = all_path,
      sep = "\t",
      quote = FALSE,
      row.names = FALSE
    )
    return(list(
      result_dir = result_dir,
      variant_all = all_path,
      files = rows,
      status = "no_barcodes"
    ))
  }

  variant_list <- list()
  for (i in seq_along(barcode_dirs)) {
    barcode_dir <- barcode_dirs[[i]]
    barcode <- basename(barcode_dir)
    vcf <- file.path(barcode_dir, "variants", variant_vcf_name)
    out_tsv <- file.path(barcode_dir, variant_tsv_name)

    if (!file.exists(vcf)) {
      rows$status[[i]] <- "missing_vcf"
      warning("Variant VCF not found for `", barcode, "`: ", vcf, call. = FALSE)
      next
    }

    variant <- read_vcf(
      vcf_file = vcf,
      reference_fasta = reference,
      flank_width = flank_width
    )
    if (is.null(variant)) {
      variant <- empty_variant_table(variant_columns)
      rows$status[[i]] <- "no_variants"
    } else {
      variant <- add_variant_reference_name_columns(variant, reference_map)
      variant <- subset_variant_columns(variant, variant_columns)
      rows$status[[i]] <- "written"
    }
    rows$n_variants[[i]] <- nrow(variant)

    utils::write.table(
      variant,
      file = out_tsv,
      sep = "\t",
      quote = FALSE,
      row.names = FALSE
    )
    rows$variant_tsv[[i]] <- normalizePath(out_tsv, mustWork = TRUE)
    variant_list[[barcode]] <- variant
  }

  variant_all <- if (length(variant_list) == 0L) {
    empty_variant_table(variant_columns)
  } else {
    do.call(rbind, unname(variant_list))
  }
  rownames(variant_all) <- NULL
  utils::write.table(
    variant_all,
    file = all_path,
    sep = "\t",
    quote = FALSE,
    row.names = FALSE
  )

  list(
    result_dir = result_dir,
    variant_all = normalizePath(all_path, mustWork = TRUE),
    files = rows,
    status = "written"
  )
}

subset_variant_columns <- function(variant, variant_columns) {
  missing_cols <- setdiff(variant_columns, names(variant))
  for (col in missing_cols) {
    variant[[col]] <- NA
  }
  variant[, variant_columns, drop = FALSE]
}

empty_variant_table <- function(variant_columns) {
  as.data.frame(
    stats::setNames(rep(list(logical()), length(variant_columns)), variant_columns),
    stringsAsFactors = FALSE,
    check.names = FALSE
  )
}

make_variant_reference_name_map <- function(original_reference, sanitized_reference) {
  check_file_arg(original_reference, "original_reference")
  check_file_arg(sanitized_reference, "sanitized_reference")
  original <- Biostrings::readDNAStringSet(original_reference)
  sanitized <- Biostrings::readDNAStringSet(sanitized_reference)
  original_names <- names(original)
  sanitized_names <- names(sanitized)
  if (is.null(original_names) || any(!nzchar(original_names))) {
    stop("All FASTA records in `original_reference` must have names.",
         call. = FALSE)
  }
  if (is.null(sanitized_names) || any(!nzchar(sanitized_names))) {
    stop("All FASTA records in `sanitized_reference` must have names.",
         call. = FALSE)
  }
  if (length(original) != length(sanitized)) {
    warning(
      "`original_reference` and `sanitized_reference` contain different numbers of records; ",
      "reference name mapping may be incomplete.",
      call. = FALSE
    )
  }

  n <- min(length(original), length(sanitized))
  if (n == 0L) {
    return(data.frame(
      reference_name_sanitized = character(),
      reference_name_original = character(),
      stringsAsFactors = FALSE
    ))
  }

  data.frame(
    reference_name_sanitized = sanitized_names[seq_len(n)],
    reference_name_original = original_names[seq_len(n)],
    stringsAsFactors = FALSE
  )
}

add_variant_reference_name_columns <- function(variant, reference_map) {
  variant$reference_name_sanitized <- variant$CHROM
  variant$reference_name_original <- variant$CHROM
  if (nrow(reference_map) == 0L || !"CHROM" %in% names(variant)) {
    return(variant)
  }

  idx <- match(variant$CHROM, reference_map$reference_name_sanitized)
  matched <- !is.na(idx)
  variant$reference_name_original[matched] <- reference_map$reference_name_original[idx[matched]]
  variant
}

resolve_wf_amplicon_variant_reference <- function(result_dir, reference, dry_run) {
  check_file_arg(reference, "reference")
  reference <- normalizePath(reference, mustWork = TRUE)
  if (isTRUE(dry_run) || !dir.exists(result_dir)) {
    return(reference)
  }

  direct_candidates <- list.files(
    result_dir,
    pattern = "^reference_sanitized_seqID[.](fa|fasta|fq|fastq)([.]gz)?$",
    full.names = TRUE,
    ignore.case = TRUE
  )
  candidates <- direct_candidates
  if (length(candidates) == 0L) {
    candidates <- list.files(
      result_dir,
      pattern = "^reference_sanitized_seqID[.](fa|fasta|fq|fastq)([.]gz)?$",
      full.names = TRUE,
      recursive = TRUE,
      ignore.case = TRUE
    )
  }
  candidates <- sort(candidates[file.exists(candidates)])

  if (length(candidates) > 0L) {
    if (length(candidates) > 1L) {
      warning(
        "Multiple sanitized reference files were found under `result_dir`; using the first: ",
        candidates[[1]],
        call. = FALSE
      )
    }
    return(normalizePath(candidates[[1]], mustWork = TRUE))
  }

  original_names <- names(Biostrings::readDNAStringSet(reference))
  if (length(original_names) > 0L &&
      any(grepl("[[:space:]]", original_names))) {
    warning(
      "No `reference_sanitized_seqID.*` file was found under `result_dir`, ",
      "but the original reference contains whitespace in sequence names. ",
      "Variant table/IGV/AB1 generation may fail if VCF/BAM sequence names were sanitized by wf-amplicon.",
      call. = FALSE
    )
  }

  reference
}

generate_variant_igv_snapshots <- function(result_dir,
                                           reference,
                                           barcode_pattern,
                                           format,
                                           igv,
                                           sort,
                                           display,
                                           max_panel_height,
                                           use_xvfb,
                                           igv_dir_name,
                                           dry_run) {
  check_file_arg(reference, "reference")
  reference <- normalizePath(reference, mustWork = TRUE)
  ref_names <- variant_reference_names(reference)
  barcode_dirs <- variant_barcode_dirs(result_dir, barcode_pattern)

  rows <- data.frame(
    barcode = character(),
    reference_name = character(),
    bam = character(),
    bai = character(),
    snapshot = character(),
    bam_exists = logical(),
    bai_exists = logical(),
    generated = logical(),
    status = character(),
    stringsAsFactors = FALSE
  )
  details <- list()

  for (barcode_dir in barcode_dirs) {
    barcode <- basename(barcode_dir)
    bam <- file.path(barcode_dir, "alignments", paste0(barcode, ".aligned.sorted.bam"))
    bai <- delivery_standard_bam_index_path(bam)
    bam_exists <- file.exists(bam)
    bai_exists <- !is.na(bai)
    igv_dir <- file.path(barcode_dir, igv_dir_name)

    for (ref_name in ref_names) {
      snapshot_name <- paste0(
        barcode,
        ".",
        sanitize_igv_snapshot_name(ref_name),
        ".",
        format
      )
      snapshot <- file.path(igv_dir, snapshot_name)

      if (isTRUE(dry_run)) {
        rows <- rbind(rows, data.frame(
          barcode = barcode,
          reference_name = ref_name,
          bam = bam,
          bai = if (is.na(bai)) paste0(bam, ".bai") else bai,
          snapshot = snapshot,
          bam_exists = bam_exists,
          bai_exists = bai_exists,
          generated = FALSE,
          status = "dry_run",
          stringsAsFactors = FALSE
        ))
        next
      }

      if (!bam_exists) {
        stop("BAM file not found for `", barcode, "`: ", bam, call. = FALSE)
      }
      if (!bai_exists) {
        stop("BAM index not found for `", barcode, "`: ", paste0(bam, ".bai"),
             call. = FALSE)
      }

      res <- igv_snapshot(
        genome_fasta = reference,
        bam = bam,
        chr = ref_name,
        out_dir = igv_dir,
        format = format,
        snapshot_name = snapshot_name,
        igv = igv,
        sort = sort,
        display = display,
        max_panel_height = max_panel_height,
        use_xvfb = use_xvfb
      )
      key <- paste(barcode, ref_name, sep = ":")
      details[[key]] <- res

      rows <- rbind(rows, data.frame(
        barcode = barcode,
        reference_name = ref_name,
        bam = bam,
        bai = bai,
        snapshot = normalizePath(snapshot, mustWork = file.exists(snapshot)),
        bam_exists = bam_exists,
        bai_exists = bai_exists,
        generated = identical(res$status, 0L),
        status = if (identical(res$status, 0L)) "generated" else paste0("status_", res$status),
        stringsAsFactors = FALSE
      ))
    }
  }

  list(files = rows, details = details)
}

