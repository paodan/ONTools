        dry_run = dry_run,
        echo = echo,
        stderr = stderr
      )
    } else {
      message("Step 8: Generate synthetic AB1 files (skipped)")
      ab1_results[[folder]] <- NULL
    }

    if (isTRUE(collect_results_step)) {
      message("Step 9: Deliver the results")
      output_dir <- file.path(path_delivery, folder, "variant_results")
      if (isTRUE(dry_run)) {
        delivery[[folder]] <- data.frame(
          label = "delivery",
          source = workflow[[folder]]$paths$out_dir,
          destination = output_dir,
          type = "directory",
          exists = dir.exists(workflow[[folder]]$paths$out_dir),
          copied = FALSE,
          stringsAsFactors = FALSE
        )
      } else {
        delivery[[folder]] <- collect_variant_results(
          result_dir = workflow[[folder]]$paths$out_dir,
          output_dir = output_dir,
          sample_map = sample_info_file,
          variant_all_name = variant_all_name,
          barcode_pattern = "^barcode[0-9]+$",
          fastq_pass_trim_dir = workflow[[folder]]$paths$fastq,
          include_execution = include_execution,
          include_igv = run_igv_step,
          include_ab1 = make_ab1,
          ab1_name_template = ab1_name_template,
          igv_dir_name = igv_dir_name,
          ab1_dir_name = ab1_dir_name,
          overwrite = overwrite_delivery
        )
        utils::write.csv(
          delivery[[folder]],
          file = file.path(path_work, paste0("variant_delivery_stats_", folder, ".csv")),
          row.names = FALSE
        )
      }
    } else {
      message("Step 9: Deliver the results (skipped)")
      delivery[[folder]] <- NULL
    }
  }

  invisible(list(
    g1 = g1,
    g2 = g2,
    stat = stat,
    move_plans = move_plans,
    workflow = workflow,
    variant_tables = variant_tables,
    variant_references = variant_references,
    igv = igv_results,
    ab1 = ab1_results,
    delivery = delivery,
    source_fastq_stats = source_fastq_stats,
    reference = reference,
    path_work = path_work,
    path_delivery = path_delivery,
    path_seq_summary = path_seq_summary,
    fig_path = fig_path,
    stat_path = stat_path
  ))
}

run_variant_dorado_steps <- function(path_proj,
                                     path_work,
                                     kit_name,
                                     model,
                                     demux_out_name,
                                     fastq_out,
                                     barcode_both_ends,
                                     run_dorado_basecall_step,
                                     run_dorado_demux_step,
                                     run_dorado_fastq_step,
                                     dorado_threads,
                                     dorado_fastq_write_md5,
                                     dorado,
                                     samtools,
                                     gzip,
                                     dorado_conda_env,
                                     conda,
                                     dry_run,
                                     echo,
                                     wait,
                                     stderr) {
  if (!isTRUE(run_dorado_basecall_step) &&
      !isTRUE(run_dorado_demux_step) &&
      !isTRUE(run_dorado_fastq_step)) {
    return(NULL)
  }

  calls_bam <- file.path(path_proj, "bam", paste0("calls_", model, ".bam"))
  demux_dir <- file.path(path_proj, demux_out_name)

  if (isTRUE(run_dorado_basecall_step)) {
    message("Step 1a: Dorado basecalling")
    basecall_stat <- dorado_basecall(
      proj = path_proj,
      model = model,
      output_bam = calls_bam,
      overwrite = TRUE,
      dorado = dorado,
      conda_env = dorado_conda_env,
      conda = conda,
      dry_run = dry_run,
      echo = echo,
      stderr = stderr
    )
  } else {
    message("Step 1a: Dorado basecalling (skipped)")
    basecall_stat <- list(
      status = NA_integer_,
      command = NA_character_,
      args = character(),
      command_string = NA_character_,
      paths = list(
        project_dir = path_proj,
        pod5_dir = file.path(path_proj, "pod5"),
        output_bam = calls_bam
      ),
      conda_env = dorado_conda_env
    )
  }

  if (isTRUE(run_dorado_demux_step)) {
    message("Step 1b: Dorado barcode demultiplexing")
    demux_stat <- dorado_demux_bam(
      calls_bam = calls_bam,
      demux_dir = demux_dir,
      kit_name = kit_name,
      barcode_both_ends = barcode_both_ends,
      emit_summary = TRUE,
      threads = dorado_threads,
      require_bam_pass = !isTRUE(dry_run),
      dorado = dorado,
      conda_env = dorado_conda_env,
      conda = conda,
      dry_run = dry_run,
      echo = echo,
      stderr = stderr
    )
  } else {
    message("Step 1b: Dorado barcode demultiplexing (skipped)")
    demux_stat <- list(
      status = NA_integer_,
      command = NA_character_,
      args = character(),
      command_string = NA_character_,
      paths = list(calls_bam = calls_bam, demux_dir = demux_dir),
      conda_env = dorado_conda_env
    )
  }

  if (isTRUE(run_dorado_fastq_step)) {
    message("Step 1c: Convert demultiplexed BAM files to FASTQ.GZ")
    if (isTRUE(dry_run) && !dorado_demux_has_bam_pass(demux_dir)) {
      fastq_stat <- list(
        status = NA_integer_,
        commands = character(),
        conversions = data.frame(
          bam_pass_dir = character(),
          barcode_dir = character(),
          barcode = character(),
          rel_path = character(),
          out_dir = character(),
          output_fastq = character(),
          n_bam = integer(),
          bam_files = I(list())
        ),
        paths = list(
          demux_dir = demux_dir,
          bam_pass_dirs = character(),
          fastq_dirs = character()
        ),
        conda_env = dorado_conda_env,
        note = "dry_run: no bam_pass directory exists yet, so FASTQ conversion commands could not be enumerated."
      )
    } else {
      fastq_stat <- dorado_bam_to_fastq(
        demux_dir = demux_dir,
        fastq_out = fastq_out,
        overwrite = TRUE,
        include_unclassified = TRUE,
        allow_empty = FALSE,
        write_md5 = dorado_fastq_write_md5,
        samtools = samtools,
        gzip = gzip,
        conda_env = dorado_conda_env,
        conda = conda,
        dry_run = dry_run,
        echo = echo,
        stderr = stderr
      )
    }
  } else {
    message("Step 1c: Convert demultiplexed BAM files to FASTQ.GZ (skipped)")
    fastq_stat <- list(
      status = NA_integer_,
      commands = character(),
      conversions = data.frame(),
      paths = list(demux_dir = demux_dir, bam_pass_dirs = character(), fastq_dirs = character()),
      conda_env = dorado_conda_env
    )
  }

  stat <- make_consensus_dorado_stat(
    proj = path_proj,
    model = model,
    demux_out = demux_out_name,
    fastq_out = fastq_out,
    basecall = basecall_stat,
    demux = demux_stat,
    fastq = fastq_stat
  )
  if (!isTRUE(dry_run) && isTRUE(wait)) {
    save(stat, file = file.path(path_work, "stat.Rdata"))
  }
  stat
}

